"""Build findings/tractates/AJ_angel_catalogue.yaml from the appendix (§14) of
*The Body That Waited for Breath* (literary-compilation, data/08_Correspondential_Texts/).

Every named office of NHC II 15,13–19,10 / IV 24–29 with its Coptic, member, grade and reading,
exactly as the thesis gives them. Run again whenever the thesis appendix changes.
Set LITCOMP to the literary-compilation checkout if it is not beside this repository.
"""
import os, re, pathlib, yaml
HERE = pathlib.Path(__file__).resolve().parent
NHL = HERE.parents[2]
LITCOMP = pathlib.Path(os.environ.get('LITCOMP', NHL.parent / 'literary-compilation'))
THESIS = LITCOMP / 'data/08_Correspondential_Texts/The Body That Waited for Breath_ The Angelic Anthropogony of the Apocryphon of John Read from the Coptic.md'
OUT = NHL / 'findings/tractates/AJ_angel_catalogue.yaml'

t = THESIS.read_text()
def section(h):
    i = t.index(h); j = t.index('\n### ', i + 1) if '\n### ' in t[i + 1:] else len(t)
    j2 = t.find('\n## ', i + 1)
    return t[i:min(x for x in (j, j2) if x > 0)]
def rows(sec):
    out = []
    for l in sec.split('\n'):
        if l.startswith('|') and not re.match(r'\|\s*-', l):
            c = [x.strip().replace('**', '') for x in l.strip().strip('|').split('|')]
            out.append(c)
    return out[1:]  # drop header

first = [dict(no=r[0], name=r[1], member=r[2], grade=r[3], reading=r[4])
         for r in rows(section('### 14.2 '))]
seven = [dict(no=r[0], name=r[1], witness=r[2], identity=r[3]) for r in rows(section('### 14.3 '))]
second = [dict(no=r[0], member=r[1], name=r[2], grade=r[3], reading=r[4]) for r in rows(section('### 14.4 '))]
rulers, grp = [], None
for r in rows(section('### 14.5 ')):
    grp = r[0] or grp
    rulers.append(dict(group=grp, office=r[1], name=r[2], grade=r[3], reading=r[4]))
counts = rows(section('### 14.6 '))

doc = {
 'title': 'Apocryphon of John — catalogue of the named offices of the body-creation passage',
 'source': ('Generated by research/apj_name_patterns/analysis/build_catalogue.py from the appendix (§14) of '
            '"The Body That Waited for Breath: The Angelic Anthropogony of the Apocryphon of John Read from the Coptic" '
            '(literary-compilation, data/08_Correspondential_Texts/). Do not edit by hand; correct the thesis and rebuild.'),
 'text': 'NHC II 15,13–19,10 and IV 24,1–29,18, Coptic of both codices (Linssen 2024)',
 'grades': {
   'A': 'transparent: the Coptic letters spell a known word without emendation, or the text glosses the name',
   'B': 'probable: a known word or name is visible in the spelling with a minimal assumption',
   'C': 'possible: needs a compound, an emendation or a sound change; offered, not relied on',
 },
 'status': ('Supersedes the etymologies of AJ_angel_name_translations.yaml wherever the two differ. '
            'Readings rest on Crum, Černý, Quack 1995, Piwowarczyk 2021 and Gundel 1936; grade-C proposals marked '
            '"proposed in this study" come from a comparison with Gundel\'s decan tables. Only grades A and B carry argument.'),
 'first_list_makers': first,
 'seven_over_the_makers': seven,
 'second_list_movers': second,
 'rulers_of_faculty_quality_passion': rulers,
 'count': [dict(group=c[0], positions=c[1], surviving=c[2], grade_A_or_B=c[3]) for c in counts],
}
OUT.write_text('# Generated file — see "source" below.\n' +
               yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=110))
print(len(first), len(seven), len(second), len(rulers), 'written', OUT)
